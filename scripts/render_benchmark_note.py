"""Render the weekly committed-before-truth benchmark note from the audit files.

Every number is computed from Data/**/ledger.jsonl and the frozen comparison
calibration — no hand-typed figures. The "standing vs the baseline" line is
generated by scripts/compare_strategies.py (the Option C panel verdict), so it
CANNOT over-claim: a superiority statement appears only when the FULL
pre-registered bar is met (sign-test significant AND pooled capture >= the
baseline's). Constraints baked in (CLAUDE.md R4 / docs/benchmark-note-template.md):
ledger-derived numbers only; no superiority claim below the bar; failures printed
as plainly as wins (a weak strategy-week shows its number; a missed day shows as a
smaller day count, never backfilled).

Markets, their display names, currencies, and public/private status come from the
registry (talea.markets) — the single source of truth — so a new public
market appears here automatically.

Run: uv run python scripts/render_benchmark_note.py [--week-end YYYY-MM-DD]
                                                    [--window-days 7] [--out PATH]
Default week-end = the current ES market day; default out = stdout.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from talea import loop  # noqa: E402
from talea.markets import MARKETS, public_markets  # noqa: E402
import compare_strategies as cmp  # noqa: E402

PRIMARY = "battery-2h2h-persistence"
NAMES = {"battery-2h2h-persistence": "persistence",
         "battery-2h2h-climatology": "climatology",
         "battery-2h2h-rankblend": "rankblend",
         "battery-2h2h-weekly": "weekly"}
SYMBOL = {"EUR": "€", "USD": "$"}
MIRROR_URL = "github.com/ArturoQuintana/spain-dayahead-ledger"  # until a brand exists


# --- data ---

def load_settled(ledger_path: Path) -> list[dict]:
    """Settled ledger rows (those carrying a realized pnl_eur), oldest first."""
    if not ledger_path.exists():
        return []
    out = []
    for line in ledger_path.read_text().splitlines():
        line = line.strip()
        if line and "pnl_eur" in (r := json.loads(line)):
            out.append(r)
    return out


def has_receipts(receipts_path: Path) -> bool:
    """Has this market committed at least one receipt? The file existing is
    not enough: a pass refused at the moment of writing leaves the file it had
    opened, empty, and a market with an empty file has opened no ledger."""
    if not receipts_path.exists():
        return False
    for line in receipts_path.read_text().splitlines():
        if line.strip():
            try:
                if isinstance(json.loads(line), dict):
                    return True
            except json.JSONDecodeError:
                continue
    return False


def window_bounds(week_end: date, window_days: int) -> tuple[str, str]:
    """Inclusive [start, end] ISO strings for the trailing window."""
    return (week_end - timedelta(days=window_days - 1)).isoformat(), week_end.isoformat()


def summarize(rows_in_window: list[dict]) -> dict[str, dict]:
    """Per strategy over the window: day count, mean daily capture (matching the
    `status` command's mean-of-daily convention), mean P&L/day, days net-positive."""
    agg: dict[str, dict] = {}
    for r in rows_in_window:
        a = agg.setdefault(r["strategy"], {"n": 0, "pnl": 0.0, "caps": [], "wins": 0})
        a["n"] += 1
        a["pnl"] += r["pnl_eur"]
        if r["pnl_eur"] > 0:
            a["wins"] += 1
        if r.get("capture") is not None:
            a["caps"].append(r["capture"])
    return {s: {"n": a["n"],
                "mean_pnl": a["pnl"] / a["n"] if a["n"] else 0.0,
                "capture": (sum(a["caps"]) / len(a["caps"]) if a["caps"] else None),
                "wins": a["wins"]}
            for s, a in agg.items()}


# --- formatting ---

def fmt_money(x: float, currency: str) -> str:
    sym = SYMBOL.get(currency)
    return f"{sym}{x:,.2f}" if sym else f"{x:,.2f} {currency}"


def _cap_str(c: float | None) -> str:
    return f"{c * 100:.1f}%" if c is not None else "—"


def render_market_section(market, week_end: date, window_days: int) -> tuple[str, int]:
    """Markdown table for one market over the window. Returns (md, n_settled_days);
    n=0 means the caller should footnote the market instead."""
    start_iso, end_iso = window_bounds(week_end, window_days)
    win = [r for r in load_settled(market.ledger_path) if start_iso <= r["target"] <= end_iso]
    summ = summarize(win)
    if not summ:
        return "", 0
    unit = SYMBOL.get(market.currency, market.currency)
    title = market.presentation.title or market.slug
    n_days = max(d["n"] for d in summ.values())
    lines = [f"**{title}** — {n_days} settled days\n",
             f"| Strategy | Capture | Mean {unit}/day | Days net-positive |",
             "|---|--:|--:|--:|"]
    # capture desc (None last), so the reader sees the week ranked but never a
    # SUPERIORITY claim (that lives only in the standing line, gated by the bar).
    for s, d in sorted(summ.items(),
                       key=lambda kv: -(kv[1]["capture"] if kv[1]["capture"] is not None else -1.0)):
        name = NAMES.get(s, s)
        label = f"{name} *(baseline)*" if s == PRIMARY else name
        lines.append(f"| {label} | {_cap_str(d['capture'])} | "
                     f"{fmt_money(d['mean_pnl'], market.currency)} | {d['wins']} / {d['n']} |")
    return "\n".join(lines) + "\n", n_days


def comparison_line(all_settled: list[dict], cal: dict | None = None) -> str:
    """The 'standing vs the baseline' line. COUNTS ONLY, by construction.
    Under Amendment 1 (ratified 2026-11-10) a comparison is decided only at a
    month-end review; between reviews nothing may show a p-value or a verdict.
    A weekly note is never a decision look, so this line cannot declare a
    winner — it reports wins, ties and losses and says where decisions are made.
    `cal` is accepted for the old call signature and is not used."""
    conf = cmp.confirmatory_look(all_settled, None)
    parts = [
        "Standing is decided only at month-end reviews, under the pre-registered "
        "rules; this note reports counts, never a verdict.",
        f"Climatology vs persistence (the one confirmatory comparison, decided once "
        f"on its first {conf['target_n']} non-tied days): {conf['wins']} wins, "
        f"{conf['losses']} losses, {conf['ties']} ties — "
        f"{min(conf['n'], conf['target_n'])} of {conf['target_n']}."]
    look = cmp.market_look(cmp.CONFIRMATORY["market"], all_settled, None,
                           primary=cmp.PERSISTENCE)
    since = [f"{NAMES.get(c['a'], c['a'])} {c['wins']}W-{c['ties']}T-{c['losses']}L"
             for c in look["comparisons"]
             if c["rule"] == "R1" and not c["confirmatory"] and c["shared"]]
    if since:
        parts.append("Against persistence, on days settled since the rules were "
                     "amended (2026-11-11): " + "; ".join(since) + ".")
    return " ".join(parts)


# --- the note ---

STANDFIRST = (
    "*An independent, tamper-evident record of naive day-ahead battery-arbitrage "
    "strategies. Every decision is hash-committed and Bitcoin-anchored **before** "
    "the day-ahead auction publishes, so nothing in this record can be back-edited, "
    "cherry-picked, or fitted after the fact. Anyone can re-derive every number "
    "below from the public audit files.*")

BAR_BOX = (
    "> *The bar (pre-registered; amended 2026-11-10):* a strategy is declared to "
    "beat the persistence baseline only at a month-end review, on ≥30 shared "
    "non-tied days settled after 2026-11-11, with a one-sided sign-test `p_eff` "
    "(`max(p_iid, p_boot)`) at 0.05/12 per review, Holm-corrected within the "
    "market, **and** pooled capture ≥ the baseline's. The one confirmatory "
    "comparison (climatology vs persistence, Spain) is decided once, on its first "
    "90 non-tied days, at 0.05. Until a review decides, differences are reported, "
    "never ranked.")

METHOD = (
    "<sub>**Method.** Simulated 1 MW / 2 MWh unit, buy the 2 cheapest hours, sell "
    "the 2 dearest, 85% round-trip efficiency, €0.50/MWh fees — all "
    "recorded in every receipt. Decisions are committed against the previous day's "
    "prices before the D+1 auction publishes (~13:15 CET); a receipt for day T is "
    "refused if any price for T already exists (leak guard). Records are "
    "append-only; a missed day stays missing, never backfilled. Strategies: "
    "*persistence* (yesterday's shape), *climatology* (trailing-28-day per-hour "
    "mean), *rankblend* (mean of the two legs' hour-ranks), *weekly* (same hour "
    "last week). Not investment advice; paper-traded, no capital at risk.</sub>")


def render_note(week_end: date, window_days: int, markets: list, cal: dict | None,
                mirror_url: str = MIRROR_URL) -> str:
    start_iso, end_iso = window_bounds(week_end, window_days)
    sections, opened_only = [], []
    for m in markets:
        sec, n = render_market_section(m, week_end, window_days)
        if n:
            sections.append(sec)
        elif load_settled(m.ledger_path) or has_receipts(m.receipts_path):
            opened_only.append(m.presentation.tab_name or m.slug)

    # The standing line uses the primary (mature) market's FULL ledger — the bar
    # is about full shared history, not one week.
    primary_market = next(m for m in MARKETS.values() if m.primary)
    standing = comparison_line(load_settled(primary_market.ledger_path), cal)

    parts = [f"### Committed-before-truth benchmark — week of {end_iso}", "",
             STANDFIRST, "", f"**This week ({start_iso} → {end_iso})**", ""]
    parts.append("\n".join(sections))
    if opened_only:
        parts += ["", "*(Also live, ledgers opened and first settled results due "
                  "in a coming note: " + ", ".join(opened_only) + ".)*"]
    parts += ["", "- **Capture** = realized P&L ÷ perfect-hindsight (oracle) "
              "P&L on the same day. **Mean** and **days net-positive** are over "
              "settled days in the window. A strategy shows fewer days when it "
              "needs more history (*weekly* needs d−7; *rankblend* needs both "
              "legs).", ""]
    parts += [f"**Standing vs the baseline.** {standing}", "", BAR_BOX, "",
              "**Verify it yourself.** Don't trust this note — check it:", "",
              f"1. Clone the public ledger: `{mirror_url}`",
              "2. Re-derive every figure: `python scripts/verify_ledger.py --all`",
              "3. Confirm the receipts were committed before the auction: each "
              "carries an OpenTimestamps proof anchored to Bitcoin "
              "(`Data/**/ots/`); a read-only third party re-checks the whole "
              "ledger weekly.", "", METHOD, ""]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Render the weekly benchmark note.")
    ap.add_argument("--week-end", help="YYYY-MM-DD (default: current ES market day)")
    ap.add_argument("--window-days", type=int, default=7)
    ap.add_argument("--out", help="write here (default: stdout)")
    a = ap.parse_args(argv)
    week_end = date.fromisoformat(a.week_end) if a.week_end else loop.market_today()
    note = render_note(week_end, a.window_days, public_markets(), cmp.load_calibration())
    if a.out:
        Path(a.out).write_text(note)
        print(f"wrote {a.out}")
    else:
        sys.stdout.write(note)
    return 0


if __name__ == "__main__":
    sys.exit(main())
